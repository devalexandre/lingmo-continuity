// Layout edges closer than this (in layout pixels) touch
static constexpr int kTouch = 8;

static int percent(double v)
{
    return qBound(0, int(std::lround(v * 100.0)), 100);
}

// The part of [a0, a1) shared with [b0, b1), as fractions of each side
static bool overlap(int a0, int a1, int b0, int b1, Link &link)
{
    const int o0 = qMax(a0, b0), o1 = qMin(a1, b1);
    // Less than 2% shared: a corner touch, no link
    if (o1 - o0 <= qMax(4, int(0.02 * qMin(a1 - a0, b1 - b0))))
        return false;
    link.s0 = percent(double(o0 - a0) / (a1 - a0));
    link.s1 = percent(double(o1 - a0) / (a1 - a0));
    link.d0 = percent(double(o0 - b0) / (b1 - b0));
    link.d1 = percent(double(o1 - b0) / (b1 - b0));
    return link.s1 > link.s0 && link.d1 > link.d0;
}

QList<Link> links(const QList<Computer> &computers)
{
    QList<Link> out;
    for (const Computer &a : computers) {
        const QRect &A = a.rect;
        for (const Computer &b : computers) {
            if (&a == &b || a.name == b.name)
                continue;
            const QRect &B = b.rect;
            Link l;
            l.from = a.name;
            l.to = b.name;
            const int aRight = A.x() + A.width(), aBottom = A.y() + A.height();
            const int bRight = B.x() + B.width(), bBottom = B.y() + B.height();
            if (std::abs(aRight - B.x()) <= kTouch && overlap(A.y(), aBottom, B.y(), bBottom, l)) {
                l.dir = QStringLiteral("right");
            } else if (std::abs(A.x() - bRight) <= kTouch && overlap(A.y(), aBottom, B.y(), bBottom, l)) {
                l.dir = QStringLiteral("left");
            } else if (std::abs(A.y() - bBottom) <= kTouch && overlap(A.x(), aRight, B.x(), bRight, l)) {
                l.dir = QStringLiteral("up");
            } else if (std::abs(aBottom - B.y()) <= kTouch && overlap(A.x(), aRight, B.x(), bRight, l)) {
                l.dir = QStringLiteral("down");
            } else {
                continue;
            }
            out.append(l);
        }
    }
    return out;
}

static QString range(int a, int b)
{
    return (a == 0 && b == 100) ? QString() : QStringLiteral("(%1,%2)").arg(a).arg(b);
}

QString serverConfig(const QList<Computer> &computers, const Options &options)
{
    QString text;
    QTextStream s(&text);
    s << "# Generated by lingmo-continuity from the layout in Settings; edits are overwritten.\n";
    s << "section: links\n";
    const QList<Link> all = links(computers);
    for (const Computer &c : computers) {
        s << "\t" << c.name << ":\n";
        for (const Link &l : all) {
            if (l.from == c.name)
                s << "\t\t" << l.dir << range(l.s0, l.s1) << " = " << l.to << range(l.d0, l.d1) << "\n";
        }
    }
    s << "end\n\n";
    s << "section: options\n";
    if (isValidHotkey(options.lockHotkey))
        s << "\tkeystroke(" << options.lockHotkey << ") = lockCursorToScreen(toggle)\n";
    if (isValidHotkey(options.switchHotkey))
        s << "\tkeystroke(" << options.switchHotkey << ") = switchToNextScreen\n";
    s << "end\n";
    return text;
}

QString neighbourAt(const QList<Computer> &computers, const QString &from, const QString &dir, double fraction)
{
    const int pct = percent(qBound(0.0, fraction, 1.0));
    for (const Link &l : links(computers)) {
        if (l.from == from && l.dir == dir && pct >= l.s0 && pct <= l.s1)
            return l.to;
    }
    return {};
}

bool writeSettings(const QString &path, const Settings &st)
{
    QDir().mkpath(QFileInfo(path).absolutePath());
    QFile::remove(path);
    {
        QSettings ini(path, QSettings::IniFormat);
        ini.setValue(QStringLiteral("core/coreMode"), st.mode == QLatin1String("server") ? 2 : 1);
        ini.setValue(QStringLiteral("core/computerName"), st.name);
        ini.setValue(QStringLiteral("core/port"), st.port);
        ini.setValue(QStringLiteral("core/processMode"), 0);
        ini.setValue(QStringLiteral("core/preventSleep"), false);
        // TLS always on, and only certificates paired in Settings get in
        ini.setValue(QStringLiteral("security/tlsEnabled"), true);
        ini.setValue(QStringLiteral("security/checkPeerFingerprints"), true);
        ini.setValue(QStringLiteral("security/certificate"), st.certificate);
        ini.setValue(QStringLiteral("security/keySize"), 2048);
        ini.setValue(QStringLiteral("log/level"), st.logLevel);
        ini.setValue(QStringLiteral("log/toFile"), false);
        ini.setValue(QStringLiteral("gui/enableUpdateCheck"), false);
        if (st.mode == QLatin1String("server")) {
            ini.setValue(QStringLiteral("server/externalConfig"), true);
            ini.setValue(QStringLiteral("server/externalConfigFile"), st.serverConfig);
            ini.setValue(QStringLiteral("server/enableClipboard"), st.options.clipboard);
            ini.setValue(QStringLiteral("server/clipboardSize"), 3);
            const bool delay = st.options.switchMode == QLatin1String("delay");
            const bool tap = st.options.switchMode == QLatin1String("doubletap");
            ini.setValue(QStringLiteral("server/enableSwitchDelay"), delay);
            ini.setValue(QStringLiteral("server/switchDelay"), st.options.switchDelay);
            ini.setValue(QStringLiteral("server/enableSwitchDoubleTap"), tap);
            ini.setValue(QStringLiteral("server/switchDoubleTap"), st.options.doubleTap);
            // No lock key: Scroll Lock must not lock the cursor either
            ini.setValue(QStringLiteral("server/disableLockToComputer"), !isValidHotkey(st.options.lockHotkey));
            ini.setValue(QStringLiteral("server/protocol"), QStringLiteral("barrier"));
            for (const QString &c : st.computers)
                ini.setValue(QStringLiteral("computer_%1/name").arg(c), c);
        } else {
            ini.setValue(QStringLiteral("client/remoteHost"), st.remoteHost);
            ini.setValue(QStringLiteral("client/languageSync"), true);
        }
        ini.sync();
        if (ini.status() != QSettings::NoError)
            return false;
    }
    QFile::setPermissions(path, QFile::ReadOwner | QFile::WriteOwner);
    return true;
}

bool writeTrustFile(const QString &path, const QStringList &fingerprints)
{
    QDir().mkpath(QFileInfo(path).absolutePath());
    QSaveFile f(path);
    if (!f.open(QIODevice::WriteOnly))
        return false;
    f.setPermissions(QFile::ReadOwner | QFile::WriteOwner);
    for (const QString &fp : fingerprints) {
        if (!fp.isEmpty())
            f.write("v2:sha256:" + fp.toLower().toLatin1() + "\n");
    }
    return f.commit();
}

QStringList readTrustFile(const QString &path)
{
    QStringList out;
    QFile f(path);
    if (!f.open(QIODevice::ReadOnly))
        return out;
    while (!f.atEnd()) {
        const QString line = QString::fromLatin1(f.readLine()).trimmed();
        if (line.startsWith(QLatin1String("v2:sha256:")))
            out << line.mid(10).toUpper();
    }
    return out;
}

static const QStringList &modifierNames()
{
    static const QStringList names{QStringLiteral("shift"), QStringLiteral("control"), QStringLiteral("alt"),
                                   QStringLiteral("meta"), QStringLiteral("super"), QStringLiteral("altgr")};
    return names;
}

bool isValidHotkey(const QString &key)
{
    if (key.isEmpty())
        return false;
    static const QRegularExpression keyName(QStringLiteral("^([A-Za-z][A-Za-z0-9_]*|[0-9]|\\\\u[0-9A-Fa-f]{4})$"));
    const QStringList parts = key.split(QLatin1Char('+'));
    for (int i = 0; i < parts.size() - 1; ++i) {
        if (!modifierNames().contains(parts.at(i).toLower()))
            return false;
    }
    return keyName.match(parts.last()).hasMatch();
}

QString hotkeyLabel(const QString &key)
{
    if (!isValidHotkey(key))
        return {};
    static const QHash<QString, QString> pretty{
        {QStringLiteral("shift"), QStringLiteral("Shift")},     {QStringLiteral("control"), QStringLiteral("Ctrl")},
        {QStringLiteral("alt"), QStringLiteral("Alt")},         {QStringLiteral("meta"), QStringLiteral("Meta")},
        {QStringLiteral("super"), QStringLiteral("Super")},     {QStringLiteral("altgr"), QStringLiteral("AltGr")},
        {QStringLiteral("ScrollLock"), QStringLiteral("Scroll Lock")},
        {QStringLiteral("Right"), QStringLiteral("→")},         {QStringLiteral("Left"), QStringLiteral("←")},
        {QStringLiteral("Up"), QStringLiteral("↑")},            {QStringLiteral("Down"), QStringLiteral("↓")},
    };
    QStringList out;
    for (const QString &p : key.split(QLatin1Char('+')))
        out << pretty.value(p, pretty.value(p.toLower(), p.size() == 1 ? p.toUpper() : p));
    return out.join(QLatin1Char('+'));
}

